function cityFromZone(tz: string): string {
  const segments = tz.split("/");
  return segments[segments.length - 1].replace(/_/g, " ");
}

export const TIMEZONE_GROUPS: TzCountryGroup[] = (() => {
  const groups: TzCountryGroup[] = [
    { country: "UTC", zones: [{ tz: "UTC", city: "UTC" }] },
  ];

  Object.keys(ZONES_BY_COUNTRY)
    .map((code) => ({
      code,
      name: COUNTRY_NAMES[code] ?? code,
    }))
    .sort((a, b) => a.name.localeCompare(b.name))
    .forEach(({ code, name }) => {
      const zones = ZONES_BY_COUNTRY[code]
        .map((tz) => ({ tz, city: cityFromZone(tz) }))
        .sort((a, b) => a.city.localeCompare(b.city));
      groups.push({ country: name, zones });
    });

  return groups;
})();
