// All IANA timezones grouped by country.
//
// Source: the tzdb `zone1970.tab` country->zone mapping plus ISO-3166 country
// names. Data is static so it works in every browser regardless of
// `Intl.supportedValuesOf` support. `config.timezone` on the clock widget stays
// a raw IANA string (e.g. "America/New_York"), so the stored shape and the
// Flutter renderer contract are unchanged — this file only drives the picker UI.

export interface TzEntry {
  /** IANA zone id, e.g. "America/New_York". */
  tz: string;
  /** Human label derived from the zone id, e.g. "New York". */
  city: string;
}

export interface TzCountryGroup {
  country: string;
  zones: TzEntry[];
}

